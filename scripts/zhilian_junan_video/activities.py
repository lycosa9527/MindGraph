def _visit_scenes() -> tuple[ActivityScene, ...]:
    return ACTIVITY_SCENES + TEACHER_SCENES


def activity_line(scene_id: str) -> str:
    """Spoken line for one activity clip. Mouth sync uses this exact sentence."""
    for item in _visit_scenes():
        if item["id"] == scene_id:
            return item["line"]
    raise KeyError(scene_id)


