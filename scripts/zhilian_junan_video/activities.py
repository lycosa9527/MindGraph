def activity_filename(scene_id: str) -> str:
    """Published mp4 name in tour order."""
    try:
        return ACTIVITY_FILENAMES[scene_id]
    except KeyError as exc:
        raise KeyError(scene_id) from exc


def activity_source_for_filename(filename: str) -> str:
    """Client still used for the slow push in front of one published clip."""
    for item in _visit_scenes():
        if ACTIVITY_FILENAMES.get(item["id"]) == filename:
            return item["source"]
    raise KeyError(filename)
