def opening_still_prompt(prompt: str) -> str:
    """Keep only the first two sentences so n=1 stills do not stack later beats."""
    parts = [part.strip() for part in prompt.split("。") if part.strip()]
    if len(parts) >= 2:
        return f"{parts[0]}。{parts[1]}。"
    if parts:
        return f"{parts[0]}。"
    return prompt


def zone_by_id(zone_id: str) -> BattleZone:
    """Look up a zone by 01 or 01-desk-stare."""
    needle = zone_id.strip()
    for zone in BATTLE_ZONES:
        packed = f"{zone['id']}-{zone['slug']}"
        if needle in {zone["id"], packed}:
            return zone
    raise ValueError(f"Unknown battle zone: {zone_id}")


def catalog_ids() -> tuple[str, ...]:
    """Packed ids in storyboard order."""
    return tuple(f"{zone['id']}-{zone['slug']}" for zone in BATTLE_ZONES)
