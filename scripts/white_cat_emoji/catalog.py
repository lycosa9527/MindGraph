def clip_name(action: RoleAction) -> str:
    """Desktop filename stem, e.g. 11-clap_鼓掌欢呼."""
    return f"{action['id']}-{action['slug']}_{action['name']}"


def action_by_id(action_id: str) -> RoleAction:
    """Look up a clip by 01 or 01-look-here."""
    needle = action_id.strip()
    for action in EMOJI_ACTIONS:
        if action["id"] == needle or clip_name(action).startswith(needle):
            return action
    raise ValueError(f"Unknown white-cat emoji: {action_id}")


def catalog_ids() -> tuple[str, ...]:
    """Packed ids in prompt order."""
    return tuple(f"{action['id']}-{action['slug']}" for action in EMOJI_ACTIONS)
